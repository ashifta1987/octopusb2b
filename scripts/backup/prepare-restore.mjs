#!/usr/bin/env node
// Prepares SQL for a FULL restore into a target Supabase database (scratch / staging / production):
//   --roles in.sql --roles-out out.sql   CREATE ROLE statements made idempotent (re-runs on a scratch project)
//   --reset-out reset.sql                wipes the target's app data first: public + recovery schemas, auth users, storage metadata
//   --post-out post.sql [--maintenance]  runs after the data load (keeps maintenance mode ON for production restores)
// Then the workflow runs (Supabase's documented restore order, one transaction):
//   psql --single-transaction -v ON_ERROR_STOP=1 -f reset.sql -f roles.sql -f schema.sql -c 'SET session_replication_role = replica' -f data.sql -f post.sql
import fs from 'node:fs';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };

if (flag('--roles') && flag('--roles-out')) {
  const src = fs.readFileSync(flag('--roles'), 'utf8');
  const out = src.replace(/^CREATE ROLE ([^;]+);$/gm, (_, r) => `DO $$ BEGIN CREATE ROLE ${r}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
  fs.writeFileSync(flag('--roles-out'), out);
}

if (flag('--reset-out')) {
  fs.writeFileSync(
    flag('--reset-out'),
    `-- generated by scripts/backup/prepare-restore.mjs: wipe the target before loading the backup
set local storage.allow_delete_query = 'true';
drop schema if exists recovery cascade;
drop schema if exists public cascade;
create schema public;
alter schema public owner to pg_database_owner;
grant usage on schema public to postgres, anon, authenticated, service_role;
-- auth: users first (children cascade), then any remaining auth data except the auth service's own migrations
delete from auth.users;
do $$ declare t text; begin
  for t in select tablename from pg_tables where schemaname = 'auth' and tablename not in ('schema_migrations', 'users') loop
    execute format('delete from auth.%I', t);
  end loop;
end $$;
-- storage metadata (files are re-uploaded by scripts/backup/storage.mjs)
do $$ declare t text; begin
  foreach t in array array['objects','s3_multipart_uploads_parts','s3_multipart_uploads','prefixes','buckets_analytics','buckets'] loop
    if to_regclass('storage.' || t) is not null then execute format('delete from storage.%I', t); end if;
  end loop;
end $$;
`,
  );
}

if (flag('--post-out')) {
  const lines = ['-- generated by scripts/backup/prepare-restore.mjs: after the data load', 'SET session_replication_role = origin;'];
  if (args.includes('--maintenance')) {
    // the restored site_settings row reflects the backup moment (maintenance off) — keep the app in maintenance until the workflow finishes
    lines.push(
      `update public.site_settings set value = jsonb_set(jsonb_set(value, '{enabled}', 'true'), '{since}', to_jsonb(now())) where key = 'maintenance_mode';`,
    );
  }
  fs.writeFileSync(flag('--post-out'), lines.join('\n') + '\n');
}
